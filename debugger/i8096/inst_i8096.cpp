// The 80C196KB adds the unimplemented opcode vector at 2012H and the upper
// interrupt vectors at 2030H-203FH; the 80C196KC the PTS vectors up to
// 205DH, as the 80C196NP; the 80296SA has no PTS.
bool isVector(uint16_t addr, CpuType cpu) {
    if (cpu == CPU_8096)
        return addr >= 0x2000 && addr < 0x2012;
    const uint16_t upperEnd =
            cpu == CPU_80C196KC || cpu == CPU_80C196NP ? 0x205E : 0x2040;
    return (addr >= 0x2000 && addr < 0x2014) ||
           (addr >= 0x2030 && addr < upperEnd);
}

template <uint_fast8_t N>
bool contains(const uint8_t (&opcodes)[N], uint_fast8_t opc) {
    for (const auto o : opcodes) {
        if (opc == o)
            return true;
    }
    return false;
}

// The earliest CPU that has |opc|.
CpuType cpuOf(uint_fast8_t opc) {
    if (contains(SA_OPCODES, opc))
        return CPU_80296SA;
    if (contains(KC_OPCODES, opc))
        return CPU_80C196KC;
    if (contains(KB_OPCODES, opc))
        return CPU_80C196KB;
    return CPU_8096;
}

int16_t signExtend(uint16_t u16, uint_fast8_t width) {
    const auto sign = UINT16_C(1) << (width - 1);
    const auto mask = (sign << 1) - 1;
    return static_cast<int16_t>(((u16 + sign) & mask) - sign);
}

const uint8_t *page_FE(uint_fast8_t opc) {
    const auto hi = opc >> 4;
    const auto lo = (opc >> 2) & 3;
    if (hi < 0x4 || hi >= 0xA || lo != 3)
        return nullptr;
    const auto index = ((hi - 0x4) << 2) + (opc & 3);
    return &PAGEFE_TABLE[index];
}

