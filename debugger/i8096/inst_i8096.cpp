bool InstI8096::indexAddressing(uint_fast8_t opc) {
    // XCH and XCHB too
    return (opc >= 0x40 && opc < 0xD0 && (opc & 3) == 3) || opc == 0x0B ||
           opc == 0x1B;
}

// |_seq|, or a relocating MAC's at |pc|.
// ATTENTION: the 80296SA's RPT, an AND 3op to 04H, repeats the next
// instruction, which no sequence models.
const char *InstI8096::macRelocates(uint16_t pc, const MatchMemory *mems) const {
    const char *seq;
    switch (_opc) {
    case 0x4E:
        seq = MACR_3IN;
        break;
    case 0x4F:
        seq = MACR_3IX;
        break;
    case 0x6E:
        seq = MACR_2IN;
        break;
    case 0x6F:
        seq = MACR_2IX;
        break;
    default:
        return _seq;
    }
    auto len = MatchWalker::instructionBytes(_seq);
    if (indexAddressing(_opc) && (mems->read_byte(pc + 1) & 1))
        ++len;  // the long index's
    const auto dest = mems->read_byte(pc + len - 1);
    return dest < 0x10 && (dest & 4) ? seq : _seq;
}

bool InstI8096::set(uint16_t pc, const MatchMemory *mems, CpuType cpu) {
    _opc = mems->read_byte(pc++);
    if (cpu < cpuOf(_opc))
        return false;
    // The 80296SA has no PTS: DPTS and EPTS are unimplemented opcodes.
    if (cpu == CPU_80296SA && (_opc == DPTS || _opc == EPTS))
        return false;
    auto row = &PAGE00_TABLE[_opc];
    if (_opc == 0xFE) {
        _opc = mems->read_byte(pc++);
        row = page_FE(_opc);
    }
    _seq = row ? SEQUENCES[*row] : "";
    if (*_seq == 0)
        return false;
    if (cpu == CPU_80296SA && row == &PAGE00_TABLE[_opc])
        _seq = macRelocates(pc - 1, mems);
    if (indexAddressing(_opc) && (mems->read_byte(pc) & 1))
        _seq = strchr(_seq, '/') + 1;  // the long index
    if (_opc == TRAP && pushesBeforeVector(cpu))
        _seq = TRAP_C196;
    return true;
}

uint_fast8_t InstI8096::instLength() const {
    return MatchWalker::instructionBytes(_seq);
}

MatchWalker::Kind ArchI8096::cycleKind(const SignalsImpl *impl) const {
    const auto s = static_cast<const SignalsI8096 *>(impl);
    return s->read()    ? MatchWalker::K_READ
           : s->write() ? MatchWalker::K_WRITE
                        : MatchWalker::K_NONE;
}

// J goes to the next + disp: an 11-bit one in SJMP's and SCALL's opcode
// and first byte, a JBC's, JBS's, DJNZ's or DJNZW's in its last byte, a
// Jcc's in its first; LJMP's and LCALL's 16 bits, the low 16 of an
// 80296SA's EJMP's and ECALL's 24 in 64-Kbyte mode; RST's to the reset
// origin.
bool ArchI8096::decode(uint32_t pc, MatchWalker::Decoded &inst) const {
    pc &= 0xFFFF;
    InstI8096 i;
    if (!i.set(pc, _mems, _cpu))
        return false;
    inst.pc = pc;
    inst.seq = i.sequence();
    inst.length = i.instLength();
    auto read = [&](uint32_t addr) { return _mems->read_byte(addr & 0xFFFF); };
    const auto opc = read(pc);
    const auto next = pc + inst.length;
    const auto disp1 = read(pc + 1);
    inst.hasEa = false;
    inst.hasTarget = true;
    if (opc >= 0x20 && opc < 0x30) {
        inst.target = next + signExtend(((opc & 7) << 8) | disp1, 11);
    } else if ((opc >= 0x30 && opc < 0x40) || opc == 0xE0 || opc == 0xE1) {
        inst.target = next + static_cast<int8_t>(read(pc + 2));
    } else if (opc >= 0xD0 && opc < 0xE0) {
        inst.target = next + static_cast<int8_t>(disp1);
    } else if (opc == 0xE7 || opc == 0xEF ||
               (_cpu == CPU_80296SA && (opc == 0xE6 || opc == 0xF1))) {
        inst.target = next + static_cast<int16_t>(disp1 | read(pc + 2) << 8);
    } else if (opc == 0xFF) {
        inst.target = InstI8096::ORG_RESET;
    } else {
        inst.hasTarget = false;
    }
    inst.target &= 0xFFFF;
    return true;
}

bool ArchI8096::isVectorTable(uint32_t addr) const {
    return isVector(addr, _cpu);
}

const char *ArchI8096::interruptSequence() const {
    return InstI8096::pushesBeforeVector(_cpu) ? INTERRUPT_C196 : INTERRUPT;
}

void ArchI8096::markCycle(
        SignalsImpl *impl, MatchWalker::Role, uint_fast8_t) const {
    static_cast<SignalsI8096 *>(impl)->clearMark();
}

void ArchI8096::markStart(SignalsImpl *s, uint32_t pc) const {
    static_cast<SignalsI8096 *>(s)->markStart(pc);
}

